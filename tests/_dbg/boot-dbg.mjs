import { chromium } from 'playwright';
const base = process.env.PWK_BASE_URL || 'http://localhost:4174/';
const browser = await chromium.launch();
const page = await browser.newPage();
const errs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text().slice(0, 300)); });
page.on('pageerror', (e) => errs.push('PAGEERROR: ' + String(e && e.stack || e).slice(0, 600)));
page.on('requestfailed', (r) => errs.push('REQFAIL: ' + r.url()));
await page.goto(base, { waitUntil: 'load' });
await page.waitForTimeout(4000);
const state = await page.evaluate(() => ({ G: typeof window.G, createPoke: typeof window.createPoke, startBattle: typeof window.startBattle, PW_VERSION: window.PW_VERSION, booted: !!(window.G && window.G.team), title: document.title, bodyClasses: document.body.className.slice(0, 100) }));
console.log(JSON.stringify(state));
console.log(errs.slice(0, 15).join('\n'));
await browser.close();

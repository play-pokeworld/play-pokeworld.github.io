import { chromium } from 'playwright';
const BASE = process.env.PWK_BASE_URL || 'http://localhost:4174/';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 820 } });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(BASE, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.PokeWorldGameStarted === false || window.PokeWorldGameStarted === true, null, { timeout: 15000 });
await page.evaluate(() => window.createNewSaveFromMenu && window.createNewSaveFromMenu());
await page.waitForSelector('#starter-modal', { state: 'visible', timeout: 8000 });
await page.evaluate(() => { const b = document.querySelector('#starter-modal [data-call*="pickStarter"], #starter-modal .starter-card, #starter-modal button'); b && b.click(); });
await page.waitForFunction(() => window.PokeWorldGameStarted === true, null, { timeout: 8000 });
await page.waitForFunction(() => window.__pwScreensReady === true, null, { timeout: 20000 });
await page.waitForTimeout(500);
const r = await page.evaluate(async () => {
  const out = {};
  window.clickLocation('route1');
  await new Promise((r) => setTimeout(r, 300));
  window.exploreArea();
  await new Promise((r) => setTimeout(r, 1500));
  out.battleActive = !!battle.active;
  out.enemy = battle.enemyPoke && battle.enemyPoke.name;
  // Wound the team mid-battle then end the battle
  G.team[0].currentHP = 1;
  G.team[0].status = 'brn';
  out.before = G.team[0].currentHP;
  window.endBattle();
  await new Promise((r) => setTimeout(r, 300));
  out.after = G.team[0].currentHP;
  out.max = G.team[0].maxHP;
  out.status = G.team[0].status;
  out.logHasHeal = (battle.log || []).some((l) => /soign|healed|prêt/i.test(String(l.text || l)));
  out.logTail = (battle.log || []).slice(-3).map((l) => String(l.text || l).slice(0, 80));
  out.tutoTargets = [...document.querySelectorAll('.pw-tuto-target')].map((e) => e.tagName + (e.id ? '#' + e.id : '') + ' ' + (e.getAttribute('data-call') || e.getAttribute('data-call-args') || ''));
  return out;
});
console.log(r);
console.log('errors', errors);
await browser.close();

/**
 * @file gen-battle-doc.mjs
 * @brief Writes docs/BATTLE_VOCABULARY.md: every effect kind of the three data vocabularies
 * (moves, talents, held items) with its number of users, a real example from the generated
 * tables and its engine coverage state (systems/battle/BattleEffectCoverage.js).
 * Run by build-all.mjs after the tables are written, or alone: node tools/data/gen-battle-doc.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { PROJECT_ROOT } from './TableWriter.mjs';

const load = (relative) => import(pathToFileURL(path.join(PROJECT_ROOT, relative)).href);

const EXAMPLE_MAX_LENGTH = 90;

/**
 * @param {Record<string, string>} kinds
 * @param {Record<string, string>} coverage
 * @param {Array<[string, Object]>} entries - [owner id, effect]
 * @returns {string[]}
 */
function table(kinds, coverage, entries) {
  const lines = ['| Kind | Users | Example | Engine |', '|---|---|---|---|'];
  for (const kind of Object.values(kinds)) {
    const users = entries.filter(([, effect]) => effect.kind === kind);
    let example = '—';
    if (users.length > 0) {
      let shape = JSON.stringify(users[0][1]).replace(/"/g, '');
      if (shape.length > EXAMPLE_MAX_LENGTH) shape = `${shape.slice(0, EXAMPLE_MAX_LENGTH - 1)}…`;
      example = `\`${users[0][0]}\` \`${shape}\``;
    }
    lines.push(`| \`${kind}\` | ${users.length} | ${example} | ${coverage[kind]} |`);
  }
  return lines;
}

export async function generateBattleDoc() {
  const { MoveDB } = await load('src/data/battle/MoveDB.js');
  const { TalentDB } = await load('src/data/pokemon/TalentDB.js');
  const { ItemDB } = await load('src/data/items/ItemDB.js');
  const { MoveEffectKinds } = await load('src/data/battle/MoveEffectKinds.js');
  const { TalentEffectKinds } = await load('src/data/battle/TalentEffectKinds.js');
  const { HeldEffectKinds } = await load('src/data/items/HeldEffectKinds.js');
  const coverage = await load('src/systems/battle/BattleEffectCoverage.js');
  const moveEffects = MoveDB.getInstance().getAll().flatMap((move) => move.effects.map((effect) => [move.id, effect]));
  const talentEffects = TalentDB.getInstance().getAll().flatMap((talent) => talent.effects.map((effect) => [talent.id, effect]));
  const heldEffects = ItemDB.getInstance().getAll().filter((item) => item.effect).map((item) => [item.id, item.effect]);
  const lines = [
    '# Battle effect vocabulary (generated)',
    '',
    'Generated by `tools/data/gen-battle-doc.mjs`. Semantics and deviations: `docs/BATTLE_EFFECTS.md`.',
    'Engine: `ported` = implemented, `deferred` = original effect not implemented yet,',
    '`no_battle` = no effect inside a battle.',
    '',
    '## Move effects (`moves-data.js`, `MoveEffectKinds`)',
    '',
    ...table(MoveEffectKinds, coverage.MOVE_EFFECT_COVERAGE, moveEffects),
    '',
    '## Talent effects (`talents-data.js`, `TalentEffectKinds`)',
    '',
    ...table(TalentEffectKinds, coverage.TALENT_EFFECT_COVERAGE, talentEffects),
    '',
    '## Held item effects (`items-data.js`, `HeldEffectKinds`)',
    '',
    ...table(HeldEffectKinds, coverage.HELD_EFFECT_COVERAGE, heldEffects),
    ''
  ];
  fs.writeFileSync(path.join(PROJECT_ROOT, 'docs/BATTLE_VOCABULARY.md'), lines.join('\n'));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generateBattleDoc();

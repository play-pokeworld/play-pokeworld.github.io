/**
 * @file build-all.mjs
 * @brief Regenerates every data table of src/data/raw/ from the original game repository and
 * writes docs/DATA_COVERAGE.md (what could not be ported automatically).
 *
 * Usage: node tools/data/build-all.mjs <original repository root>
 *        (npm run data -- <original repository root>)
 */

import fs from 'fs';
import path from 'path';
import { OriginalSource } from './OriginalSource.mjs';
import { PROJECT_ROOT } from './TableWriter.mjs';
import { generateSpecies } from './gen-species.mjs';
import { generateTalents } from './gen-talents.mjs';
import { generateMoves } from './gen-moves.mjs';
import { generateItems } from './gen-items.mjs';
import { generateWorld } from './gen-world.mjs';
import { generateQuests } from './gen-quests.mjs';
import { generateBalls } from './gen-balls.mjs';
import { generateTrainers } from './gen-trainers.mjs';
import { generateShops } from './gen-shops.mjs';

const root = process.argv[2];
if (!root) {
  console.error('usage: node tools/data/build-all.mjs <original repository root>');
  process.exit(1);
}
const source = new OriginalSource(root);

const species = await generateSpecies(source);
const talents = await generateTalents(source);
const moves = await generateMoves(source);
const items = await generateItems(source);
const world = await generateWorld(source);
const quests = await generateQuests(source);
const balls = await generateBalls(source);
const trainers = await generateTrainers(source);
const shops = await generateShops(source);

const lines = [
  '# Data coverage (generated)',
  '',
  'Generated by `tools/data/build-all.mjs`. Lists what the generators could not turn into',
  'declarative data; the battle engine ignores these parts until they are ported by hand.',
  '',
  '## Counts',
  '',
  '| Table | Entries |',
  '|---|---|',
  `| species-data.js | ${species.speciesCount} |`,
  `| forms-data.js | ${species.formCount} |`,
  `| talents-data.js | ${talents.count} |`,
  `| moves-data.js | ${moves.count} |`,
  `| items-data.js | ${items.count} |`,
  `| locations-data.js / map-layout-data.js | ${world.counts.locations} / ${world.counts.layout} |`,
  `| encounters-data.js | ${world.counts.encounters} |`,
  `| quests-data.js | ${quests.count} |`,
  `| ball-filter-presets-data.js | ${balls.count} |`,
  `| trainers-data.js / leagues-data.js | ${trainers.trainers} / ${trainers.leagues} |`,
  `| shops-data.js | ${shops.count} |`,
  '',
  `## Talents without effects (${talents.notPorted.length})`,
  '',
  talents.notPorted.map((id) => `\`${id}\``).join(', ') || 'none',
  '',
  `## Moves whose description is not covered by data (${moves.notPorted.length})`,
  '',
  '| Move | Original description |',
  '|---|---|',
  ...moves.notPorted.map(({ id, desc }) => `| \`${id}\` | ${String(desc).replace(/\|/g, '/')} |`),
  '',
  `## Items without image (${items.missingImages.length})`,
  '',
  items.missingImages.map((id) => `\`${id}\``).join(', ') || 'none',
  '',
  `## Quest reward items unknown to the original item table (${quests.droppedRewardItems.length})`,
  '',
  'The original grantRewardItem() silently skipped them; they are dropped from quests-data.js.',
  '',
  quests.droppedRewardItems.map(({ quest, item }) => `\`${quest}\` → \`${item}\``).join(', ') || 'none',
  '',
  `## Trainer data notes (${trainers.problems.length})`,
  '',
  ...trainers.problems.map((problem) => `- ${problem}`),
  '',
  `## Shop stock dropped: unknown item or no price, skipped by the original too (${shops.dropped.length})`,
  '',
  shops.dropped.map(({ shop, item }) => `\`${shop}\` → \`${item}\``).join(', ') || 'none',
  '',
  `## Species without sprite (${species.missingSprites.length})`,
  '',
  species.missingSprites.map((id) => `\`${id}\``).join(', ') || 'none',
  ''
];
fs.writeFileSync(path.join(PROJECT_ROOT, 'docs/DATA_COVERAGE.md'), lines.join('\n'));
console.log(`species=${species.speciesCount} forms=${species.formCount} talents=${talents.count} moves=${moves.count} items=${items.count} locations=${world.counts.locations} quests=${quests.count}`);
console.log(`not ported: talents=${talents.notPorted.length} moves=${moves.notPorted.length}`);

// The vocabulary doc reads the tables through the repositories: import after they are written.
const { generateBattleDoc } = await import('./gen-battle-doc.mjs');
await generateBattleDoc();

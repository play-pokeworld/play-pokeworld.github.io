#!/usr/bin/env python3
"""Passe 50 — REPAIR of the TM/HM disks (`tm_<type>.png`).

Reported symptom: "all the TM sprites are still missing, they can be
found on PokeChill's GitHub".

Cause: `download_assets.py` does know the right PokeChill URLs
(`img/items/tm<Type>.png`) but `write_download()` NEVER REPLACES an
existing file. And `main()` first bakes grey "TM" dots as
fallback (`make_placeholder`): on the first run, the placeholders won the
race and the real disks were never downloaded again.

This script forces fetching the 18 official PokeChill disks and
REPLACES any detected placeholder (grey 40×40 dot without meaningful
transparency). It also checks that every source URL answers, and reports
those that would have become invalid.

Idempotent: a real disk already in place is not downloaded again.
Usage: python3 tools/repair-tm-sprites.py [--force] [--check-only]
"""
from __future__ import annotations

import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/assets/images/items'
UA = 'PokeWorldAssetDownloader/1.0 (+tm sprites)'
POKECHILL = 'https://raw.githubusercontent.com/play-pokechill/play-pokechill.github.io/main'

TM_TYPES = ['Normal', 'Fire', 'Water', 'Grass', 'Electric', 'Ice', 'Fighting',
            'Poison', 'Ground', 'Flying', 'Psychic', 'Bug', 'Rock', 'Ghost',
            'Dragon', 'Dark', 'Steel', 'Fairy']


def fetch(url: str) -> bytes | None:
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            data = r.read()
            if r.status == 200 and len(data) > 80 and data[:8] == b'\x89PNG\r\n\x1a\n':
                return data
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError):
        return None
    return None


def is_placeholder(path: Path) -> bool:
    """Dot generated by make_placeholder(): 40×40, very few colors
    (flat background + text), no disc roundness. The real PokeChill disks
    are 32×32 and much richer."""
    if not path.exists():
        return True
    try:
        from PIL import Image
        im = Image.open(path).convert('RGBA')
    except Exception:
        return True
    if im.size == (40, 40):
        return True
    colors = {px for px in im.getdata() if px[3] > 0}
    return len(colors) <= 6


def main() -> int:
    force = '--force' in sys.argv
    check = '--check-only' in sys.argv
    got = kept = failed = 0
    bad_urls = []
    for ty in TM_TYPES:
        dest = OUT / f'tm_{ty.lower()}.png'
        url = f'{POKECHILL}/img/items/tm{ty}.png'
        if not force and not is_placeholder(dest):
            kept += 1
            continue
        data = fetch(url)
        if not data:
            failed += 1
            bad_urls.append(url)
            continue
        if check:
            got += 1
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
        got += 1
    verb = 'available' if check else 'downloaded'
    print(f'TM/HM disks: {got} {verb} · {kept} already correct · {failed} failure(s)')
    for u in bad_urls:
        print('  ✖ URL invalide :', u)
    return 1 if failed else 0


if __name__ == '__main__':
    raise SystemExit(main())
